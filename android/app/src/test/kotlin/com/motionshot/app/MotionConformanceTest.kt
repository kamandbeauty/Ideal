    @Test
    fun transitionsKeepCoverageInvariant() {
        for (type in TransitionType.values()) {
            for (step in 0..20) {
                val p = step / 20.0
                val layers = transitionDrawLayers(
                    listOf(
                        TimelineLayer(0, 1.0, LayerRole.OUT, p, type),
                        TimelineLayer(1, 0.5, LayerRole.IN, p, type),
                    ),
                )
                assertEquals("${type.id} at p=$p has 2 layers", 2, layers.size)
                when (type) {
                    TransitionType.CROSS_DISSOLVE, TransitionType.FADE,
                    TransitionType.ZOOM_TRANSITION, TransitionType.SMOOTH_ZOOM,
                    TransitionType.BLUR_TRANSITION, TransitionType.NONE,
                    -> assertClose(1.0, layers[0].alpha + layers[1].alpha, 1e-9, "${type.id} alpha sum")
                    TransitionType.SLIDE_LEFT, TransitionType.SLIDE_RIGHT -> {
                        val span = abs(layers[1].offsetX - layers[0].offsetX)
                        assertClose(1.0, span, 1e-9, "${type.id} tiling")
                    }
                    TransitionType.FADE_TO_BLACK ->
                        assertTrue("${type.id} over 1", layers[0].alpha + layers[1].alpha <= 1.0 + 1e-9)
                }
                // Inside the open transition window (0 < p < 1) Timeline.drawLayersAt
                // must also emit two active layers for every non-NONE transition.
                if (type != TransitionType.NONE && step in 1..19) {
                    val timeline = Timeline(
                        listOf(2.0, 2.0),
                        listOf(TransitionSpec(type, 1.0)),
                    )
                    assertEquals(2, timeline.drawLayersAt(1.5 + p).size)
                }
            }
        }
    }

