    @Test
    fun exportRequestParserRejectsMalformedPayloads() {
        // Odd dimensions must be rejected (4:2:0 chroma requirement).
        assertThrows(ExportRequestException::class.java) {
            ExportRequest.fromJson(
                """{"outputPath":"/tmp/a.mp4","width":1921,"height":1080,"fps":30,"photos":[]}""",
            )
        }
        // Out-of-range fps must be rejected.
        assertThrows(ExportRequestException::class.java) {
            ExportRequest.fromJson(
                """{"outputPath":"/tmp/a.mp4","width":1920,"height":1080,"fps":0,"photos":[]}""",
            )
        }
        // Valid 1-photo request parses and validates cleanly.
        val valid = ExportRequest.fromJson(
            """
            {
              "projectId": "p1",
              "projectSeed": 42,
              "outputPath": "/tmp/out.mp4",
              "width": 1920,
              "height": 1080,
              "fps": 30,
              "codec": "h264",
              "bitrate": 8000000,
              "aspect": 1.7777777777777777,
              "totalDuration": 4.0,
              "frameCount": 120,
              "photos": [{
                "id": "ph0",
                "path": "/tmp/ph0.jpg",
                "width": 4000,
                "height": 3000,
                "duration": 4.0,
                "order": 0,
                "rotationDegrees": 0,
                "motionType": "zoomIn",
                "intensity": 0.6,
                "expectedFitIw": 0.8888888888888888,
                "expectedFitIh": 0.6666666666666666,
                "keyframes": [
                  {"time": 0.0, "x": 0.0, "y": 0.0, "scale": 1.1, "rotation": 0.0, "easing": "smoother"},
