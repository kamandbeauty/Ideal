/**
 * Conformance tests: the Kotlin renderer must produce the same numbers as the
 * Python reference and the Dart preview.
 *
 * The golden JSON files under `test/resources` are generated by
 * `tools/validate` (`python3 -m motionshot.verify`). If these tests pass, the
 * exported MP4 frames and the on-screen preview agree by construction.
 */
class MotionConformanceTest {

    private fun golden(name: String): JSONObject {
        val stream = javaClass.classLoader!!.getResourceAsStream("$name.json")
        assertNotNull("missing golden/$name.json", stream)
        return JSONObject(stream!!.bufferedReader().readText())
    }

    private fun assertClose(expected: Double, actual: Double, tol: Double, what: String) {
        assertTrue("$what: expected $expected, got $actual", abs(expected - actual) <= tol)
    }

    @Test
    fun easingMatchesReference() {
        val g = golden("easing")
        for (kind in listOf("linear", "easeIn", "easeOut", "easeInOut", "smooth", "smoother")) {
            val rows = g.getJSONArray(kind)
            val easing = when (kind) {
                "linear" -> Easing.LINEAR
                "easeIn" -> Easing.EASE_IN
                "easeOut" -> Easing.EASE_OUT
                "easeInOut" -> Easing.EASE_IN_OUT
                "smooth" -> Easing.SMOOTH
                else -> Easing.SMOOTHER
            }
            for (i in 0 until rows.length()) {
                val row = rows.getJSONArray(i)
                assertClose(row.getDouble(1), ease(easing, row.getDouble(0)), 1e-9, kind)
            }
        }
        val custom = g.getJSONArray("custom")
        val curve = doubleArrayOf(0.25, 0.1, 0.25, 1.0)
        for (i in 0 until custom.length()) {
            val row = custom.getJSONArray(i)
            assertClose(
                row.getDouble(1),
                ease(Easing.CUSTOM, row.getDouble(0), curve),
                1e-9,
                "custom",
            )
        }
        val customEz = g.getJSONArray("custom_ez")
        val curveEz = doubleArrayOf(0.42, 0.0, 0.58, 1.0)
        for (i in 0 until customEz.length()) {
            val row = customEz.getJSONArray(i)
            assertClose(
                row.getDouble(1),
                ease(Easing.CUSTOM, row.getDouble(0), curveEz),
                1e-9,
                "custom_ez",
            )
        }
    }

