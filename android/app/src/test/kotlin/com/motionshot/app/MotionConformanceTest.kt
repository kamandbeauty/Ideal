    @Test
    fun cameraMathMatchesReference() {
        val g = golden("camera")
        val vp = Viewport(16.0 / 9.0)
        val fit = ImageFit.make(4000, 3000, vp)
        assertClose(g.getJSONObject("viewport16x9").getDouble("vw"), vp.vw, 1e-12, "vw")
        assertClose(g.getJSONObject("fit4000x3000").getDouble("iw"), fit.iw, 1e-12, "iw")
        val rows = g.getJSONArray("rows")
        for (i in 0 until rows.length()) {
            val m = rows.getJSONObject(i)
            val rot = m.getDouble("rotation")
            val (bw, bh) = halfExtent(vp, 1.5, rot)
            assertClose(m.getDouble("bw"), bw, 1e-12, "bw")
            assertClose(m.getDouble("bh"), bh, 1e-12, "bh")
            assertClose(m.getDouble("minScale"), minScaleAtRotation(fit, vp, rot), 1e-12, "minScale")
            val (mx, my) = maxPan(fit, vp, 1.5, rot)
            assertClose(m.getDouble("maxPanX"), mx, 1e-12, "maxPanX")
            assertClose(m.getDouble("maxPanY"), my, 1e-12, "maxPanY")
            val clamped = clampCamera(CameraState(0.9, -0.9, 1.5, rot), fit, vp)
            val expected = m.getJSONArray("clamped")
            assertClose(expected.getDouble(0), clamped.x, 1e-12, "clamped x")
            assertClose(expected.getDouble(1), clamped.y, 1e-12, "clamped y")
        }
    }

    @Test
    fun allMotionTypesStayInsideTheImage() {
        val vp = Viewport(16.0 / 9.0)
        val fit = ImageFit.make(4032, 3024, vp)
        for (type in MotionType.values()) {
            val rng = Xorshift128Plus(RandomMotion.photoSeed(7L, type.id, 0))
            val profile = com.motionshot.app.motion.MotionGenerator.generate(
                type = type,
                intensityIn = 0.8,
                duration = 6.0,
                fit = fit,
                vp = vp,
                rng = rng,
                seed = 7L,
            )
            val interp = MotionInterpolator(profile.keyframes, fit, vp)
            for (i in 0..60) {
                val st = interp.sample(6.0 * i / 60.0)
                val (bw, bh) = halfExtent(vp, st.scale, st.rotation)
                assertTrue("${type.id} sample $i exceeds image width", bw <= fit.iw + 1e-9)
                assertTrue("${type.id} sample $i exceeds image height", bh <= fit.ih + 1e-9)
                assertTrue("${type.id} sample $i scale below 1", st.scale >= 1.0 - 1e-9)
            }
            assertEquals(0.0, profile.keyframes.first().time, 0.0)
            assertEquals(6.0, profile.keyframes.last().time, 1e-12)
        }
    }

