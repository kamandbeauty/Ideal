create function public.create_receipt_upload(b uuid,u uuid,amount bigint,reference text,note text,mime_type text) returns table(receipt_id uuid,object_path text)
language plpgsql security definer set search_path='' as $$
declare rid uuid:=gen_random_uuid(); path text; begin
 if auth.uid() is null or not public.is_unit_resident(b,u) then raise exception 'Not authorized' using errcode='42501'; end if;
 if amount is null or amount not between 1 and 1000000000000 or length(btrim(coalesce(reference,''))) not between 1 and 120 or length(coalesce(note,''))>1000 or mime_type not in ('image/jpeg','image/png','image/webp') or mime_type is null then raise exception 'Invalid receipt'; end if;
 path:=b::text||'/'||rid::text;
 insert into public.payment_receipts(id,building_id,unit_id,submitted_by,amount,reference,note,mime_type,object_path) values(rid,b,u,auth.uid(),amount,btrim(reference),coalesce(note,''),mime_type,path);
 return query select rid,path;
end $$;
create function public.submit_receipt(rid uuid) returns void language plpgsql security definer set search_path='' as $$
declare r public.payment_receipts%rowtype; begin
 select * into r from public.payment_receipts where id=rid for update;
 if not found or r.submitted_by<>auth.uid() or not public.is_unit_resident(r.building_id,r.unit_id) then raise exception 'Not authorized' using errcode='42501'; end if;
 if r.status='submitted' then return; end if;
 if r.status<>'uploading' or not exists(select 1 from storage.objects o where o.bucket_id='apartment-yar-receipts' and o.name=r.object_path) then raise exception 'Uploaded image not found'; end if;
 update public.payment_receipts set status='submitted',submitted_at=now() where id=rid;
 insert into public.audit_logs(building_id,actor_id,action,entity_type,entity_id) values(r.building_id,auth.uid(),'submit','payment_receipt',rid);
end $$;
create function public.review_receipt(b uuid,rid uuid,decision text,p_note text) returns void language plpgsql security definer set search_path='' as $$ begin
 perform public.require_finance_manager(b);
 if decision not in ('reviewed','rejected') or decision is null or length(coalesce(p_note,''))>1000 then raise exception 'Invalid review'; end if;
 update public.payment_receipts set status=decision,manager_note=coalesce(p_note,''),reviewed_at=now() where id=rid and building_id=b and status='submitted';
 if not found then raise exception 'Receipt not awaiting review'; end if;
 insert into public.audit_logs(building_id,actor_id,action,entity_type,entity_id,details) values(b,auth.uid(),'review','payment_receipt',rid,jsonb_build_object('status',decision));
end $$;
