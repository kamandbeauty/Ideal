  static CaptionPreset byId(String? id) {
    if (id == null) return forLanguage('fa').first;
    for (final CaptionPreset preset in all) {
      if (preset.id == id) return preset;
    }
    return forLanguage('fa').first;
  }

  static List<CaptionPreset> forLanguage(String language) => all
      .where((CaptionPreset preset) => preset.language == language)
      .toList(growable: false);

  static List<CaptionPreset> forCategory(String category, String language) {
    final List<CaptionPreset> pool = forLanguage(language);
    if (category == 'همه') return pool;
    return pool.where((CaptionPreset preset) => preset.category == category).toList(growable: false);
  }

