#!/usr/bin/env python3
"""Generate the 10 narrator clips with nimaone/persian_tts (ONNX, offline CPU).

PRIMARY path: import the vendored OnnxTts engine and synthesize each line with
the built-in female reference voice `voices/female_narration.wav`.
FALLBACK: this sandbox cannot reach huggingface.co (the ~469 MB ONNX weights
live there), so if the package is absent the already-rendered clips in
`vo/` are kept and the attempt is recorded in `tts-attempt.log`.

Usage:
  .venv/bin/python motion/kamand-vox/audio/generate-vo-persian-tts.py
"""
import sys
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent.parent
VENDOR = ROOT / "third_party" / "persian_tts"
PKG = VENDOR / "model" / "onnx"
V2 = VENDOR / "model" / "v2"
VO = HERE / "vo"
LOG = HERE / "tts-attempt.log"

# Diacritized for correct Iranian-Farsi pronunciation.
LINES = [
    "اَبْروها، قَبْل از هَر آرایشی، اَوَّلین چیزی هَستَن که دیده میشَن.",
    "اَمّا خیلی از ژِلها، یِه لایِهٔ سَفید روشون میذارَن.",
    "کَمَنْد، یِه ژِلِ لیفْتِ اَبْرویِ کامِلاً گِیاهیه.",
    # Client-specified pronunciation: "Bedoon sefidak" / "Bedoon rizesh"
    # (no ezafe kasra after بدون). Kept undiacritized for the fallback takes.
    "بدون سفیدک",
    "بدون ریزش",
    "فَقَط کافیه اَبْروهات رو تَمیز کُنی،",
    "بُرِس بَزَنی، رو بِه بالا و بیرون.",
    "تارها، یِکی یِکی، سَرِ جاشون قَرار میگیرَن.",
    "اِستِفادهٔ آسان، نَتیجِهٔ جَذّاب.",
    "کَمَنْد؛ زِیباییِ طَبیعی، هَر روز.",
]

SEED = 20261102
VOICE = VENDOR / "voices" / "female_narration.wav"


def log(msg):
    print(msg)
    with LOG.open("a", encoding="utf-8") as f:
        f.write(msg + "\n")


def check_weights():
    missing = []
    if not (PKG / "manifest.json").exists():
        missing.append(str(PKG / "manifest.json"))
    for f in ("weights.npz", "decode_state_init.npz"):
        if not (PKG / f).exists():
            missing.append(str(PKG / f))
    for f in ("normalize_fa.py", "tokenizer_ph.model"):
        if not (V2 / f).exists():
            missing.append(str(V2 / f))
    return missing


def main():
    LOG.write_text(
        f"# Persian_tts voiceover attempt — {datetime.now(timezone.utc).isoformat()}\n"
        f"# engine: third_party/persian_tts/scripts/tts_onnx.py (OnnxTts)\n"
        f"# voice:  {VOICE.relative_to(ROOT)}\n", encoding="utf-8"
    )
    missing = check_weights()
    if missing:
        log("STATUS: ONNX package unavailable in this sandbox.")
        for m in missing:
            log(f"  missing: {m}")
        log("  reason : huggingface.co is blocked by the build sandbox network policy;")
        log("           the ~469 MB weights cannot be downloaded here.")
        log("  action : keeping the 10 fallback narrator clips already in vo/.")
        log("  to use : hf download Nimaone/pocket-tts-farsi-v2-onnx --local-dir "
             "third_party/persian_tts/model/onnx")
        log("           then re-run this script. Nothing else changes.")
        return 2

    sys.path.insert(0, str(VENDOR / "scripts"))
    sys.path.insert(0, str(V2))
    try:
        import soundfile as sf
        from tts_onnx import OnnxTts
    except ImportError as e:
        log(f"STATUS: runtime dependency missing: {e}")
        log("  install: python3 -m pip install -r requirements-persian-tts.txt")
        return 3

    eng = OnnxTts(pkg_dir=PKG, seed=SEED)
    VO.mkdir(parents=True, exist_ok=True)
    for i, text in enumerate(LINES, 1):
        audio = eng.synthesize_text(text, str(VOICE), seed=SEED + i, pace=1.0, mode="pack")
        sf.write(str(VO / f"{i:02d}.wav"), audio, eng.sample_rate)
        log(f"  {i:02d}.wav  {len(audio)/eng.sample_rate:.2f}s  synthesized with OnnxTts")
    log("STATUS: OK — all 10 clips generated by nimaone/persian_tts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
