#!/usr/bin/env node
/**
 * زمان‌بندی کلمه‌به‌کلمهٔ زیرنویس، هم‌تراز با صدای واقعیِ گوینده.
 *
 * ورودی : متنِ کیوها (content/timeline.js) + فایلِ نریشنِ خام
 * خروجی : content/words.js — برای هر کیو، آرایه‌ای از {t, d, w}
 *
 * روش: مدتِ هر کیو بین کلمه‌ها بر اساس وزنِ هجایی پخش می‌شود، بعد هر مرز
 * روی نزدیک‌ترین «درهٔ انرژی» صدا می‌نشیند (جایی که گوینده بین دو کلمه
 * نفس می‌گیرد). نتیجه، ورودِ هر کلمه دقیقاً روی هجای شنیده‌شده است.
 *
 *   node tools/words.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const PROJECT = resolve(HERE, '..');
const ROOT = resolve(PROJECT, '../..');
const VO = join(PROJECT, 'vo', 'fa.wav');

/** WAV بایت‌ها → Float32 مونو در ۲۴ کیلوهرتز */
function readWav(path) {
  const b = readFileSync(path);
  let off = 12, fmt = null, pcm = null;
  while (off + 8 <= b.length) {
    const id = b.toString('ascii', off, off + 4);
    const size = b.readUInt32LE(off + 4);
    const body = b.subarray(off + 8, off + 8 + size);
    if (id === 'fmt ') fmt = { ch: body.readUInt16LE(2), rate: body.readUInt32LE(4), bits: body.readUInt16LE(14) };
    if (id === 'data') pcm = body;
    off += 8 + size + (size % 2);
  }
  if (!fmt || !pcm) throw new Error('bad wav ' + path);
  const bytes = fmt.bits / 8;
  const n = Math.floor(pcm.length / (bytes * fmt.ch));
  const out = new Float32Array(n);
  for (let i = 0; i < n; i++) {
    let v = 0;
    for (let c = 0; c < fmt.ch; c++) {
      const p = (i * fmt.ch + c) * bytes;
      v += fmt.bits === 16 ? pcm.readInt16LE(p) / 32768
        : fmt.bits === 24 ? (pcm.readIntLE(p, 3) >> 8) / 8388608
        : pcm.readInt32LE(p) / 2147483648;
    }
    out[i] = v / fmt.ch;
  }
  return { data: out, rate: fmt.rate };
}

/** پاکتِ انرژی (RMS) با پنجرهٔ ۱۰ میلی‌ثانیه */
function envelope(x, rate) {
  const hop = Math.round(rate * 0.01);
  const n = Math.floor(x.length / hop);
  const env = new Float32Array(n);
  for (let i = 0; i < n; i++) {
    let s = 0;
    for (let j = 0; j < hop; j++) { const v = x[i * hop + j]; s += v * v; }
    env[i] = Math.sqrt(s / hop);
  }
  // هموارسازیِ سبک تا نویزِ تک‌فریمی مرز را جابه‌جا نکند
  const sm = new Float32Array(n);
  for (let i = 0; i < n; i++) {
    let s = 0, c = 0;
    for (let j = -3; j <= 3; j++) { const k = i + j; if (k >= 0 && k < n) { s += env[k]; c++; } }
    sm[i] = s / c;
  }
  return { env: sm, hop: 0.01 };
}

/** وزنِ هجایی: هر حرفِ صدادار یک هجا، کلمهٔ کوتاه حداقل نیم‌هجا */
function weight(word) {
  const clean = word.replace(/[\u200c\u200f\u064b-\u0652.,،؛:!؟«»()]/g, '');
  const vowels = (clean.match(/[اآویهٔئؤ]/g) || []).length;
  return Math.max(0.75, clean.length * 0.42 + vowels * 0.35);
}

function main() {
  const { data, rate } = readWav(VO);
  const { env, hop } = envelope(data, rate);

  return import(pathToFileURL(join(PROJECT, 'content', 'timeline.js')).href).then(({ CUES }) => {
    const out = CUES.map((cue) => {
      const words = cue.text.split(/\s+/).filter(Boolean);
      const total = words.reduce((s, w) => s + weight(w), 0);
      const span = cue.end - cue.start;

      // مرزهای خام
      let t = cue.start;
      const bounds = [cue.start];
      for (const w of words) { t += (weight(w) / total) * span; bounds.push(t); }
      bounds[bounds.length - 1] = cue.end;

      // هر مرزِ داخلی روی درهٔ انرژی نزدیک می‌نشیند
      const snap = (time, lo, hi) => {
        const rad = 0.13;
        const a = Math.max(lo, time - rad), b = Math.min(hi, time + rad);
        let best = time, bestV = Infinity;
        for (let s = a; s <= b; s += hop) {
          const i = Math.round(s / hop);
          const v = env[Math.min(env.length - 1, i)] + Math.abs(s - time) * 0.012;
          if (v < bestV) { bestV = v; best = s; }
        }
        return best;
      };
      for (let i = 1; i < bounds.length - 1; i++) {
        const lo = bounds[i - 1] + 0.09;
        const hi = bounds[i + 1] - 0.09;
        if (hi > lo) bounds[i] = snap(bounds[i], lo, hi);
      }

      return words.map((w, i) => ({
        w,
        t: +bounds[i].toFixed(3),
        d: +(bounds[i + 1] - bounds[i]).toFixed(3),
      }));
    });

    const header = '// GENERATED by tools/words.mjs — word-level timings aligned to the VO.\n';
    writeFileSync(join(PROJECT, 'content', 'words.js'),
      `${header}export const WORDS = ${JSON.stringify(out)};\n`, 'utf8');

    const flat = out.flat().length;
    const tight = out.flat().filter((w) => w.d < 0.1).length;
    console.log(`  ${CUES.length} cues · ${flat} words · ${tight} shorter than 0.1s`);
    console.log('  content/words.js');
  });
}

main();
