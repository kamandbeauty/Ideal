#!/usr/bin/env python3
"""
کلمه‌به‌کلمه زمان‌بندیِ زیرنویس.

    python3 tools/word-timing.py

۱. whisper روی فایلِ صوتی، زمانِ هر کلمهٔ *شنیده‌شده* را می‌دهد
   (متنش نویزی است، ولی ریتمِ گفتار درست است)
۲. برای هر جمله (که مرزهایش قبلاً روی مکث‌های واقعی قفل شده) کلمه‌های
   متنِ تمیزِ ما روی همان ریتم پخش می‌شوند: کلمه‌ها دقیقاً همان‌جا
   روشن می‌شوند که گوینده آن‌ها را می‌گوید
۳. خروجی: content/words.js
"""
import json
import re
import sys
from pathlib import Path

from faster_whisper import WhisperModel

PROJECT = Path(__file__).resolve().parent.parent
VO = PROJECT.parent.parent / 'Generated Audio November 04, 2026 - 4_16PM.wav'
MODEL = '/tmp/models/whisper-base'
OUT = PROJECT / 'content' / 'words.js'

src = (PROJECT / 'content' / 'timeline.js').read_text()
sentences = json.loads(re.search(r'export const SENTENCES = (\[.*?\]);', src, re.S).group(1))
fps = int(re.search(r'export const FPS = (\d+);', src).group(1))
del fps

model = WhisperModel(MODEL, device='cpu', compute_type='int8')
segments, info = model.transcribe(
    str(VO), language='fa', beam_size=5, vad_filter=True, word_timestamps=True,
    condition_on_previous_text=False,
)
spoken = []
for seg in segments:
    for w in seg.words:
        if w.end > w.start:
            spoken.append((float(w.start), float(w.end)))
spoken.sort()

if not spoken:
    sys.exit('whisper found no words')

rows = []
for s in sentences:
    text = s['text']
    words = [w for w in re.split(r'\s+', text.strip()) if w]
    if not words:
        continue
    lo, hi = s['start'], s['end']
    inside = [(max(a, lo), min(b, hi)) for a, b in spoken if b > lo and a < hi]
    inside = [(a, b) for a, b in inside if b - a > 0.02]

    if inside:
        # منحنیِ زمانِ گفتار: هر لحظه = مجموعِ مدتِ کلمه‌های گفته‌شده تا آن لحظه
        cum = [0.0]
        for a, b in inside:
            cum.append(cum[-1] + (b - a))
        total = cum[-1]

        def at(frac):
            target = frac * total
            for (a, b), c0, c1 in zip(inside, cum, cum[1:]):
                if target <= c1:
                    return a + (b - a) * ((target - c0) / max(1e-6, c1 - c0))
            return inside[-1][1]
    else:
        span = max(0.2, hi - lo)

        def at(frac):
            return lo + span * frac

    n = len(words)
    times = [at(i / n) for i in range(n)] + [at(1.0)]
    for i, w in enumerate(words):
        a = round(max(lo, times[i]), 3)
        b = round(min(hi, max(a + 0.10, times[i + 1])), 3)
        rows.append([s['i'] - 1, w, a, b])

js = '// GENERATED by tools/word-timing.py — do not edit by hand.\n'
js += '// [شمارهٔ جمله، کلمه، شروع، پایان]\n'
js += 'export const WORDS = ' + json.dumps(rows, ensure_ascii=False) + ';\n'
OUT.write_text(js)

print(f'{len(rows)} words across {len(sentences)} sentences → {OUT.relative_to(PROJECT)}')
for r in rows[:8]:
    print(f'  {r[2]:6.2f}-{r[3]:6.2f}  {r[1]}')
