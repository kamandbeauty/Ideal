#!/usr/bin/env node
/**
 * تایم‌لاینِ صحنه‌ها — روی خودِ فایلِ صوتی قفل می‌شود.
 *
 *   node tools/timeline.mjs
 *
 * ۱. silencedetect مکث‌های واقعیِ گوینده را پیدا می‌کند
 * ۲. به هر پاراگراف به نسبتِ تعدادِ حرف، سهمی از زمانِ گفتار می‌رسد
 * ۳. مرزِ هر پاراگراف روی نزدیک‌ترین مکثِ واقعی «قفل» می‌شود
 * ۴. خروجی: content/timeline.js  (بدون زیرنویس — CUES خالی است)
 */
import { spawnSync } from 'node:child_process';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const PROJECT = resolve(HERE, '..');
const ROOT = resolve(PROJECT, '../..');
const FFMPEG = join(ROOT, 'node_modules', '@ffmpeg-installer', 'linux-x64', 'ffmpeg');
const VO = join(ROOT, 'Generated Audio November 04, 2026 - 4_16PM.wav');

const FPS = 30;
const TAIL = 1.1;
const MIN_SCENE = 1.25;
const SNAP_WINDOW = 2.4;

if (!existsSync(FFMPEG)) throw new Error('missing bundled ffmpeg — run npm install');
if (!existsSync(VO)) throw new Error(`missing VO: ${VO}`);

const { SCRIPT_FA } = await import(pathToFileURL(join(PROJECT, 'content', 'script.fa.js')).href);

// ---------------------------------------------------------------- speech blocks
const probe = spawnSync(FFMPEG, ['-hide_banner', '-i', VO, '-af', 'silencedetect=noise=-32dB:d=0.28', '-f', 'null', '-'], { encoding: 'utf8' });
const log = `${probe.stdout || ''}${probe.stderr || ''}`;
const events = [...log.matchAll(/silence_(start|end): ([0-9.]+)/g)].map((m) => ({ kind: `silence_${m[1]}`, t: Number(m[2]) }));
const info = spawnSync(FFMPEG, ['-hide_banner', '-i', VO], { encoding: 'utf8' });
const total = Number(`${info.stdout}${info.stderr}`.match(/Duration: (\d+):(\d+):([0-9.]+)/)?.slice(1)
  .reduce((acc, v, i) => acc + Number(v) * [3600, 60, 1][i], 0).toFixed(3));

const blocks = [];
const gaps = [];
let cur = 0;
for (const { kind, t } of events) {
  if (kind === 'silence_start') {
    if (t - cur > 0.05) blocks.push([cur, t]);
    cur = null;
    gaps.push({ start: t, end: null });
  } else if (cur === null) {
    cur = t;
    if (gaps.length) gaps[gaps.length - 1].end = t;
  }
}
if (cur !== null && total - cur > 0.05) blocks.push([cur, total]);
if (!blocks.length) throw new Error('no speech found');

const speechTotal = blocks.reduce((a, [s, e]) => a + (e - s), 0);
const toReal = (off) => {
  let acc = 0;
  for (const [s, e] of blocks) {
    const d = e - s;
    if (off <= acc + d) return s + Math.max(0, off - acc);
    acc += d;
  }
  return blocks[blocks.length - 1][1];
};

// ---------------------------------------------------------------- paragraphs
const paras = SCRIPT_FA.map((t) => t.replace(/\s+/g, ' ').trim());
const charTotal = paras.reduce((a, t) => a + t.length, 0);

let acc = 0;
const rows = paras.map((text) => {
  const a = (acc / charTotal) * speechTotal;
  acc += text.length;
  const b = (acc / charTotal) * speechTotal;
  return { text, est: [toReal(a), toReal(b)] };
});

const mid = (g) => (g.start + (g.end ?? g.start + 0.4)) / 2;
const cands = gaps.map(mid).filter((v) => v > 0 && v < total).sort((a, b) => a - b);

// مرزها یکی‌یکی انتخاب می‌شوند: هر مرز روی نزدیک‌ترین مکثِ «هنوز استفاده‌نشده»
// می‌نشیند، به شرطی که هیچ صحنه‌ای کوتاه‌تر از MIN_SCENE نشود.
const snapped = rows.map((r) => ({ ...r, start: r.est[0], end: r.est[1] }));
snapped[0].start = 0;
let prev = 0;
for (let i = 1; i < snapped.length; i++) {
  const target = snapped[i].est[0];
  const lo = prev + MIN_SCENE;
  const hi = total - (snapped.length - i) * MIN_SCENE;
  let best = null, bestD = Infinity;
  for (const c of cands) {
    if (c < lo || c > hi) continue;
    const d = Math.abs(c - target);
    if (d < bestD) { bestD = d; best = c; }
  }
  const v = best !== null && bestD <= SNAP_WINDOW ? best : Math.min(Math.max(target, lo), hi);
  snapped[i].start = v;
  snapped[i - 1].end = v;
  prev = v;
}
snapped[snapped.length - 1].end = total;

// صحنه‌های کوتاه‌تر از MIN_SCENE به صحنهٔ قبل می‌چسبند
const merged = [];
for (const r of snapped) {
  if (merged.length && r.end - r.start < MIN_SCENE) {
    const prev = merged[merged.length - 1];
    prev.text = `${prev.text} ${r.text}`;
    prev.end = r.end;
  } else {
    merged.push({ ...r });
  }
}
merged[0].start = 0;
for (let i = 1; i < merged.length; i++) merged[i].start = merged[i - 1].end;
merged[merged.length - 1].end = total;

const filmDuration = +(total + TAIL).toFixed(3);
const frames = Math.round(filmDuration * FPS);
// عکسِ واقعی از لحظه‌ای می‌آید که راوی «لایک و دنبال‌کردن» را می‌گوید
const ctaIdx = Math.max(0, merged.findIndex((r) => r.text.includes('لایک')));
const endStart = +merged[ctaIdx].start.toFixed(3);

const js = `// GENERATED by tools/timeline.mjs — do not edit by hand.
export const FPS = ${FPS};
export const VO_DURATION = ${total.toFixed(3)};
export const DURATION = ${filmDuration};
export const FRAMES = ${frames};
export const BLOCKS = ${JSON.stringify(blocks.map(([s, e]) => [+s.toFixed(3), +e.toFixed(3)]))};
export const SENTENCES = ${JSON.stringify(merged.map((r, i) => ({ i: i + 1, text: r.text, start: +r.start.toFixed(3), end: +r.end.toFixed(3) })), null, 2)};
export const CUES = [];
export const ENDCARD = { start: ${endStart} };
`;
writeFileSync(join(PROJECT, 'content', 'timeline.js'), js);

console.log(`voice   ${total.toFixed(2)}s · ${blocks.length} speech blocks · ${speechTotal.toFixed(2)}s speaking`);
console.log(`film    ${filmDuration.toFixed(2)}s = ${frames} frames @ ${FPS}fps`);
console.log(`endcard from ${endStart.toFixed(2)}s (CTA)`);
console.log(`scenes  ${merged.length}`);
merged.forEach((s, i) => console.log(`  ${String(i + 1).padStart(2)}  ${s.start.toFixed(2).padStart(7)} → ${s.end.toFixed(2).padStart(7)}  (${(s.end - s.start).toFixed(2)}s)  ${s.text.slice(0, 44)}…`));
