#!/usr/bin/env python3
"""Generate client/Assets/Core/Text/PersianForms.gen.cs from the Unicode database.

TextMeshPro does no Arabic shaping: it draws the code points it is given. Persian is a joining
script, so before anything is drawn each letter has to be replaced by the presentation form its
neighbours imply (isolated / final / initial / medial). Those forms are ordinary Unicode characters
in U+FE70–U+FEFF and U+FB50–U+FDFF, and this script reads them out of the system's Unicode data
instead of trusting a hand-typed table.

Joining type is not in Python's unicodedata, so it is derived from the forms themselves:

    isolated + final            -> right-joining  (alef, dal, reh, zeyn, vav ...)
    isolated + final + initial + medial -> dual-joining (beh, peh, seen, kaf, gaf, lam, mim, nun ...)
    isolated only               -> non-joining (hamza)

That derivation is exactly what a shaper needs, and it cannot drift from the forms it ships with.

Usage:
    python3 tools/text/gen_persian_table.py           # write the .cs
    python3 tools/text/gen_persian_table.py --check   # verify the committed file is current
"""
from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "client" / "Assets" / "Core" / "Text" / "PersianForms.gen.cs"

# Presentation Forms-B and the Arabic Presentation Forms-A block (Persian peh/cheh/keheh/gaf/yeh
# live in Forms-A). Ligatures in Forms-A are ignored here: a ligature is not a letter form.
FORM_RANGES = [(0xFE70, 0xFEFC), (0xFB50, 0xFDFF)]
FORMS = ("isolated", "final", "initial", "medial")

# Marks that ride on the letter before them and never change joining. Value = Unicode category
# Non_Spacing_Mark, plus the Persian-specific signs that Unicode files as spacing marks.
def is_transparent(ch: str) -> bool:
    cp = ord(ch)
    if cp in (0x0640,):  # tatweel: a connector, not a mark
        return False
    if cp == 0x200C:  # ZWNJ: handled separately, it breaks joining
        return False
    if unicodedata.category(ch) in ("Mn", "Me"):
        return True
    if 0x06D6 <= cp <= 0x06ED:  # Quranic annotation signs used in Persian typesetting
        return True
    if cp in (0x0653, 0x0654, 0x0655, 0x0670):
        return True
    return False


def build() -> dict[str, dict[str, str]]:
    table: dict[str, dict[str, str]] = {}
    for lo, hi in FORM_RANGES:
        for cp in range(lo, hi + 1):
            ch = chr(cp)
            try:
                decomposition = unicodedata.decomposition(ch)
            except ValueError:
                continue
            if not decomposition or not decomposition.startswith("<"):
                continue
            tag, _, rest = decomposition.partition(">")
            tag = tag.lstrip("<").strip()
            if tag not in FORMS:
                continue
            parts = rest.split()
            if len(parts) != 1:
                continue  # a ligature (lam-alef and friends), not a letter form
            base = chr(int(parts[0], 16))
            if base == ch:
                continue
            table.setdefault(base, {})[tag] = ch
    return table


def joining_type(forms: dict[str, str]) -> str:
    if "medial" in forms and "initial" in forms:
        return "Dual"
    if "final" in forms:
        return "Right"
    return "None"


HEADER = """// <auto-generated>
//   Generated by tools/text/gen_persian_table.py from the Unicode database.
//   Do not edit by hand: run the script. CI fails if this file drifts.
//
//   TextMeshPro does not shape Arabic script, so Shazdeh.Core.Text.PersianText replaces each letter
//   with the presentation form its neighbours imply. These are the tables it needs.
// </auto-generated>
using System.Collections.Generic;

namespace Shazdeh.Core.Text
{
    /// <summary>How a letter joins to the letter after it (logical order, i.e. to its left).</summary>
    public enum JoinType : byte
    {
        /// <summary>Hamza and friends: joins nothing, always drawn isolated.</summary>
        None = 0,

        /// <summary>Alef, dal, reh, zeyn, vav: joins only to the letter before it.</summary>
        Right = 1,

        /// <summary>Beh, peh, seen, kaf, gaf, lam, mim, nun, heh, yeh: joins both ways.</summary>
        Dual = 2
    }

    public static class PersianForms
    {
        const char NoForm = '\\0';

        // Sorted by base code point so the generated file diffs cleanly.
        static readonly char[] Bases = new char[]
        {
"""


def main(argv: list[str]) -> int:
    table = build()

    # Sanity: the letters a Persian UI actually uses must all be present.
    required = "ءاآأإبپتثجچحخدذرزژسشصضطظعغفقکگلمنوهیيةؤئ"
    missing = [ch for ch in required if ch not in table or "isolated" not in table[ch]]
    if missing:
        print(f"gen_persian_table: Unicode data is missing forms for {missing}", file=sys.stderr)
        return 1

    bases = sorted(table)
    rows = {form: [] for form in FORMS}
    for base in bases:
        for form in FORMS:
            value = table[base].get(form, "\0")
            rows[form].append(value)

    def literal(chars: list[str]) -> str:
        return "".join(f"'\\u{ord(c):04X}'," for c in chars)

    def wrap(items: list[str], per_line: int = 8) -> str:
        lines = []
        for i in range(0, len(items), per_line):
            lines.append("            " + " ".join(items[i:i + per_line]))
        return "\n".join(lines)

    parts = [HEADER]
    parts.append(wrap([f"'\\u{ord(c):04X}'," for c in bases]))
    parts.append("\n        };\n\n")

    for form, title in (
        ("isolated", "Isolated"),
        ("final", "Final"),
        ("initial", "Initial"),
        ("medial", "Medial"),
    ):
        parts.append(f"        static readonly char[] {title} = new char[]\n        {{\n")
        parts.append(wrap([f"'\\u{ord(c):04X}'," for c in rows[form]]))
        parts.append("\n        };\n\n")

    joins = [joining_type(table[b]) for b in bases]
    parts.append("        static readonly JoinType[] Joins = new JoinType[]\n        {\n")
    parts.append(wrap([f"JoinType.{j}," for j in joins]))
    parts.append("\n        };\n\n")

    parts.append(
        """        static readonly Dictionary<char, int> Index = BuildIndex();

        static Dictionary<char, int> BuildIndex()
        {
            var index = new Dictionary<char, int>(Bases.Length);
            for (int i = 0; i < Bases.Length; i++) index[Bases[i]] = i;
            return index;
        }

        /// <summary>True when the character has presentation forms, i.e. it is a letter to shape.</summary>
        public static bool IsLetter(char c) => Index.ContainsKey(c);

        public static bool TryGetJoinType(char c, out JoinType joinType)
        {
            if (Index.TryGetValue(c, out int i))
            {
                joinType = Joins[i];
                return true;
            }
            joinType = JoinType.None;
            return false;
        }

        /// <summary>
        /// The form of <paramref name="c"/> for a letter that joins to the previous letter and/or the
        /// next one. Falls back to the character itself when that form does not exist (a font may have
        /// fewer forms than Unicode defines; drawing the base letter beats drawing a box).
        /// </summary>
        public static char Form(char c, bool joinsPrevious, bool joinsNext)
        {
            if (!Index.TryGetValue(c, out int i)) return c;

            char form;
            if (joinsPrevious && joinsNext) form = Medial[i];
            else if (joinsPrevious) form = Final[i];
            else if (joinsNext) form = Initial[i];
            else form = Isolated[i];

            if (form != NoForm) return form;
            if (joinsPrevious && Final[i] != NoForm) return Final[i];
            if (Isolated[i] != NoForm) return Isolated[i];
            return c;
        }

        /// <summary>The same letter without a connection to its neighbours.</summary>
        public static char Isolate(char c) => Form(c, false, false);

        /// <summary>LAM + ALEF is drawn as one glyph (U+FEFB / U+FEFC); every other pair is not.</summary>
        public const char LamAlefIsolated = '\\uFEFB';

        /// <summary>The lam-alef ligature joined to the letter before it.</summary>
        public const char LamAlefFinal = '\\uFEFC';

        /// <summary>A mark that must stay on the letter before it (harakat, hamza above, ...).</summary>
        public static bool IsTransparent(char c)
        {
            switch (c)
            {
                case '\\u064B': case '\\u064C': case '\\u064D': case '\\u064E':
                case '\\u064F': case '\\u0650': case '\\u0651': case '\\u0652':
                case '\\u0653': case '\\u0654': case '\\u0655': case '\\u0656':
                case '\\u0657': case '\\u0658': case '\\u0659': case '\\u065A':
                case '\\u065B': case '\\u065C': case '\\u065D': case '\\u065E':
                case '\\u065F': case '\\u0670': case '\\u06D6': case '\\u06D7':
                case '\\u06D8': case '\\u06D9': case '\\u06DA': case '\\u06DB':
                case '\\u06DC': case '\\u06DD': case '\\u06DE': case '\\u06DF':
                case '\\u06E0': case '\\u06E1': case '\\u06E2': case '\\u06E3':
                case '\\u06E4': case '\\u06E5': case '\\u06E6': case '\\u06E7':
                case '\\u06E8': case '\\u06E9': case '\\u06EA': case '\\u06EB':
                case '\\u06EC': case '\\u06ED': case '\\u06DF':
                    return true;
                default:
                    return false;
            }
        }

        /// <summary>Zero-width non-joiner: invisible, but it stops two letters from joining.</summary>
        public const char Zwnj = '\\u200C';

        /// <summary>Tatweel: a visible connector that joins on both sides.</summary>
        public const char Tatweel = '\\u0640';
    }
}
"""
    )

    generated = "".join(parts)
    generated = generated.replace("case '\\u06DF': case '\\u06DF':", "case '\\u06DF':")

    mode = "--check" if "--check" in argv else "write"
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""

    if mode == "--check":
        if current != generated:
            print(
                f"gen_persian_table: {OUT.relative_to(ROOT)} is stale. Run the script and commit it.",
                file=sys.stderr,
            )
            return 1
        print(f"persian forms: {len(bases)} letters, up to date")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(generated, encoding="utf-8")
    dual = sum(1 for j in joins if j == "Dual")
    right = sum(1 for j in joins if j == "Right")
    none = sum(1 for j in joins if j == "None")
    print(
        f"wrote {OUT.relative_to(ROOT)}: {len(bases)} letters "
        f"({dual} dual-joining, {right} right-joining, {none} non-joining)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
