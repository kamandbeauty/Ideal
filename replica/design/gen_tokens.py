#!/usr/bin/env python3
"""Generate Unity C# token constants from replica/design/tokens.json.

The design system lives in one file (tokens.json). Unity code must never hold a
raw hex value, a magic font size or a hard-coded duration, so this generator
writes them into a single C# class that the game imports:

    python3 replica/design/gen_tokens.py

Writes client/Assets/Game/Generated/Tokens.gen.cs (the Game assembly is the first
one allowed to touch UnityEngine; Shazdeh.Core stays engine-free). (create the folder if missing).
Standard library only. Exit code 1 if tokens.json is missing a role.
"""

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TOKENS = os.path.join(ROOT, "replica", "design", "tokens.json")
OUT = os.path.join(ROOT, "client", "Assets", "Game", "Generated", "Tokens.gen.cs")

REQUIRED = ["bg", "surface", "border", "border-input", "text", "text-muted",
            "accent", "on-accent", "danger", "success"]


def ident(name):
    """'border-input' -> 'BorderInput', 'on-accent' -> 'OnAccent'."""
    parts = re.split(r"[^0-9a-zA-Z]+", name)
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    if out[:1].isdigit():
        out = "N" + out
    return out


def hex_to_rgb(value):
    h = value.lstrip("#")
    if len(h) != 6:
        raise ValueError("expected #rrggbb, got %r" % value)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def ms(value):
    """'140ms' or '240ms cubic-bezier(...)' -> 0.14f seconds."""
    m = re.match(r"\s*(\d+(?:\.\d+)?)\s*ms", value)
    if not m:
        return None
    return "%.3f" % (float(m.group(1)) / 1000.0)


def main():
    if not os.path.exists(TOKENS):
        print("missing %s" % TOKENS, file=sys.stderr)
        return 1
    with open(TOKENS, encoding="utf-8") as f:
        t = json.load(f)

    missing = [r for r in REQUIRED if not t.get("color", {}).get(r)]
    if missing:
        print("tokens.json is missing colour roles: %s" % ", ".join(missing), file=sys.stderr)
        return 1

    lines = [
        "// <auto-generated>",
        "//   from replica/design/tokens.json — do not edit by hand.",
        "//   regenerate: python3 replica/design/gen_tokens.py",
        "// </auto-generated>",
        "using UnityEngine;",
        "",
        "namespace Shazdeh.Game",
        "{",
        "    public static class Tokens",
        "    {",
    ]

    for group, ctype in (("color", "Color"),):
        for name, value in t[group].items():
            if name.startswith("_"):
                continue
            r, g, b = hex_to_rgb(value)
            lines.append(
                "        public static readonly Color %s = new Color(%sf, %sf, %sf, 1f); // %s"
                % (ident(name), round(r / 255.0, 4), round(g / 255.0, 4), round(b / 255.0, 4), value)
            )

    if "piece" in t:
        lines += ["", "        public static class Piece", "        {"]
        for name, value in t["piece"].items():
            r, g, b = hex_to_rgb(value)
            lines.append(
                "            public static readonly Color %s = new Color(%sf, %sf, %sf, 1f); // %s"
                % (ident(name), round(r / 255.0, 4), round(g / 255.0, 4), round(b / 255.0, 4), value)
            )
        lines += ["        }", ""]

    lines += ["", "        public static class Type", "        {"]
    for name, spec in t.get("type", {}).items():
        lines.append("            public const float %s = %sf;   // line %s, weight %s"
                     % (ident(name), spec["size"], spec.get("line", "-"), spec.get("weight", "-")))
    lines += ["        }", ""]

    if "hud" in t:
        lines += ["        public static class Hud", "        {"]
        for name, value in t["hud"].items():
            if isinstance(value, dict):
                continue
            lines.append("            public const float %s = %sf;" % (ident(name), value))
        safe = t["hud"].get("safe-area", {})
        for name, value in safe.items():
            lines.append("            public const float Safe%s = %sf;" % (ident(name), value))
        lines += ["        }", ""]

    lines += ["        public static class Space", "        {"]
    for i, value in enumerate(t.get("space", [])):
        lines.append("            public const float S%d = %sf;" % (i, value))
    lines += ["        }", ""]

    lines += ["        public static class Radius", "        {"]
    for name, value in t.get("radius", {}).items():
        lines.append("            public const float %s = %sf;" % (ident(name), value))
    lines += ["        }", ""]

    lines += ["        public static class Motion", "        {"]
    for name, value in t.get("motion", {}).items():
        seconds = ms(value) if isinstance(value, str) else None
        if seconds is None:
            continue
        lines.append("            public const float %s = %sf;" % (ident(name), seconds))
    lines += ["        }"]

    lines += [
        "    }",
        "}",
        "",
    ]

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    colours = sum(1 for k in t["color"] if not k.startswith("_"))
    print("wrote %s (%d colours, %d type steps)" % (OUT, colours, len(t.get("type", {}))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
