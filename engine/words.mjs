#!/usr/bin/env node
/**
 * Word-level subtitle timing aligned to the actual recording.
 *
 *   npm run story:words -- <slug> [--lang fa|en]
 *
 * Decodes the VO to mono 24 kHz float, builds a 10 ms RMS envelope, spreads
 * each cue's words over its duration by syllable weight, then snaps every word
 * boundary onto the nearest energy valley (the narrator's micro-pause).
 * Result: the karaoke highlight lands on the syllable you actually hear.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { ROOT, ensureProjectDirs, ffmpeg, langOf, loadJs, parseArgs, project, voPath } from './lib.mjs';

const A = parseArgs();
const P = project(A);
const L = langOf(A, P);
const D = ensureProjectDirs(P);
const VO = voPath(A, P, L);
const ff = ffmpeg();
const RATE = 24000;

const perLang = join(D.content, `timeline.${L}.js`);
const { CUES } = await loadJs(existsSync(perLang) ? perLang : join(D.content, 'timeline.js'));

// ------------------------------------------------------------- decode PCM --
const raw = spawnSync(ff, [
  '-v', 'error', '-i', VO, '-vn', '-map', '0:a:0',
  '-ac', '1', '-ar', String(RATE), '-f', 'f32le', '-',
], { maxBuffer: 1024 * 1024 * 1024 });
if (raw.status !== 0 || !raw.stdout?.length) {
  throw new Error(`نتونستم صدا رو دیکود کنم: ${VO}\n${raw.stderr?.toString().slice(0, 400) || ''}`);
}
const view = new DataView(raw.stdout.buffer, raw.stdout.byteOffset, raw.stdout.byteLength);
const samples = new Float32Array(Math.floor(view.byteLength / 4));
for (let i = 0; i < samples.length; i++) samples[i] = view.getFloat32(i * 4, true);

// --------------------------------------------------------------- envelope --
const hop = Math.round(RATE * 0.01);           // 10 ms
const n = Math.floor(samples.length / hop);
const env = new Float32Array(n);
for (let i = 0; i < n; i++) {
  let s = 0;
  for (let j = 0; j < hop; j++) { const v = samples[i * hop + j]; s += v * v; }
  env[i] = Math.sqrt(s / hop);
}
const sm = new Float32Array(n);
for (let i = 0; i < n; i++) {
  let s = 0, c = 0;
  for (let j = -3; j <= 3; j++) { const k = i + j; if (k >= 0 && k < n) { s += env[k]; c++; } }
  sm[i] = s / c;
}

// ---------------------------------------------------------------- weights --
function weight(word) {
  const clean = word.replace(/[\u200c\u200f\u064b-\u0652.,،؛:!؟«»()]/g, '');
  const vowels = L === 'fa'
    ? (clean.match(/[اآویهٔئؤ]/g) || []).length
    : (clean.match(/[aeiouyAEIOUY]/g) || []).length;
  return Math.max(0.75, clean.length * (L === 'fa' ? 0.42 : 0.28) + vowels * 0.35);
}

const out = CUES.map((cue) => {
  const words = cue.text.split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  const total = words.reduce((s, w) => s + weight(w), 0) || 1;
  const span = Math.max(0.01, cue.end - cue.start);

  let t = cue.start;
  const bounds = [cue.start];
  for (const w of words) { t += (weight(w) / total) * span; bounds.push(t); }
  bounds[bounds.length - 1] = cue.end;

  const snap = (time, lo, hi) => {
    const rad = 0.13;
    const a = Math.max(lo, time - rad), b = Math.min(hi, time + rad);
    let best = time, bestV = Infinity;
    for (let s = a; s <= b; s += 0.01) {
      const i = Math.min(sm.length - 1, Math.round(s / 0.01));
      const v = sm[i] + Math.abs(s - time) * 0.012;
      if (v < bestV) { bestV = v; best = s; }
    }
    return best;
  };
  for (let i = 1; i < bounds.length - 1; i++) {
    const lo = bounds[i - 1] + 0.09;
    const hi = bounds[i + 1] - 0.09;
    if (hi > lo) bounds[i] = snap(bounds[i], lo, hi);
  }

  return words.map((w, i) => ({
    w,
    t: +bounds[i].toFixed(3),
    d: +(bounds[i + 1] - bounds[i]).toFixed(3),
  }));
});

const js = `// GENERATED by engine/words.mjs — do not edit by hand.\n` +
  `export const WORDS = ${JSON.stringify(out)};\n`;
mkdirSync(D.content, { recursive: true });
if (L === (P.config.lang || 'fa')) writeFileSync(join(D.content, 'words.js'), js);
writeFileSync(join(D.content, `words.${L}.js`), js);

const flat = out.flat();
console.log(`voice    ${relative(ROOT, VO)}`);
console.log(`words    ${CUES.length} cues · ${flat.length} words · ${flat.filter((w) => w.d < 0.1).length} shorter than 0.1s`);
console.log(`wrote    content/words.${L}.js`);
